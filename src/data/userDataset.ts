/**
 * Maps raw dataset item tokens to product catalog IDs
 */
export function mapItemTokenToProductId(token: string): string | null {
  const norm = token.trim().toLowerCase();

  if (norm === 'face wash') return 'pg-skn-01';
  if (norm === 'cleanser') return 'pg-skn-02';
  if (norm === 'toner') return 'pg-skn-03';
  if (norm === 'serum') return 'pg-skn-04';
  if (norm === 'sunscreen' || norm === 'spf50 sunscreen') return 'pg-skn-05';
  if (norm === 'face mask') return 'pg-skn-06';

  if (norm === 'foundation' || norm === 'matte foundation') return 'pg-mak-07';
  if (norm === 'concealer') return 'pg-mak-08';
  if (norm === 'lipstick') return 'pg-mak-09';
  if (norm === 'mascara') return 'pg-mak-10';
  if (norm === 'eyeliner') return 'pg-mak-11';
  if (norm === 'nail polish') return 'pg-mak-12';

  if (norm === 'shampoo' || norm === 'repair shampoo') return 'pg-bdy-13';
  if (norm === 'conditioner' || norm === 'repair conditioner') return 'pg-bdy-14';
  if (norm === 'hair mask' || norm === 'hair masks') return 'pg-bdy-15';
  if (norm === 'body wash') return 'pg-bdy-16';
  if (norm === 'body lotion') return 'pg-bdy-17';
  if (norm === 'hand cream') return 'pg-bdy-18';

  if (norm === 'perfume' || norm === 'floral perfume') return 'pg-frg-19';

  return null;
}

export function parseRawTransactions(rawList: Array<{ id: string; items: string }>): {
  transactions: Transaction[];
  rawRows: RawDatasetRow[];
} {
  const transactions: Transaction[] = [];
  const rawRows: RawDatasetRow[] = [];

  rawList.forEach((row, idx) => {
    const rawItems = row.items.split(',').map(s => s.trim()).filter(Boolean);
    const matchedIds: string[] = [];

    for (const item of rawItems) {
      const pId = mapItemTokenToProductId(item);
      if (pId && !matchedIds.includes(pId)) {
        matchedIds.push(pId);
      }
    }

    if (matchedIds.length > 0) {
      transactions.push({
        id: row.id,
        orderId: `ORD-DATA-${idx + 1}`,
        date: '2026-09-28',
        itemIds: matchedIds,
      });
    }

    rawRows.push({
      transaction_id: row.id,
      customer_id: `C${String(100 + (idx % 80)).padStart(3, '0')}`,
      transaction_date: '2026-09-28',
      products_purchased: row.items,
      type: matchedIds.length >= 3 ? 'Strong' : matchedIds.length === 2 ? 'Pair' : 'Single',
      matchedProductIds: matchedIds,
    });
  });

  return { transactions, rawRows };
}

